local L = require("targeting-data")   -- generated by scripts/targeting.py --mod
local TURRET_TYPES = {"ammo-turret", "electric-turret", "fluid-turret"}

local function base_name(name)
  return name:match("^hero%-turret%-%d+%-for%-(.+)$") or name
end

local diag = { set = 0, err = nil, readback = nil, tried = 0 }

-- The lists name every Rampant faction unit; keep only those that exist in this game, so a different faction
-- setup (or no ArmouredBiters) doesn't stop a list at its first unknown name.
local present = {}
local function list_for(base)
  if present[base] == nil then
    local list = L[base]
    if list then
      local kept = {}
      for _, name in ipairs(list) do
        if prototypes.entity[name] then kept[#kept + 1] = name end
      end
      list = #kept > 0 and kept or false
    end
    present[base] = list or false
  end
  return present[base] or nil
end

local function apply(entity)
  if not (entity and entity.valid) then return false end
  local list = list_for(base_name(entity.name))
  if not list then return false end
  local set = 0
  for i = 1, #list do
    local ok, err = pcall(function() entity.set_priority_target(i, list[i]) end)
    if not ok then
      if not diag.err then diag.err = "slot " .. i .. " on " .. entity.name .. ": " .. tostring(err) end
      break
    end
    set = set + 1
  end
  -- clear any leftover slots beyond our list
  pcall(function() for i = #list + 1, #list + 20 do entity.set_priority_target(i, nil) end end)
  diag.tried = diag.tried + 1
  if set > 0 then diag.set = diag.set + 1 end
  if not diag.readback then
    local ok, p = pcall(function() return entity.get_priority_target(1) end)
    diag.readback = ok and (p and p.name or "nil") or ("read error: " .. tostring(p))
  end
  return set > 0
end

local function apply_all(player)
  local n = 0
  for _, surface in pairs(game.surfaces) do
    for _, e in pairs(surface.find_entities_filtered{type = TURRET_TYPES, force = player.force}) do
      if apply(e) then n = n + 1 end
    end
  end
  player.print({"rtt.applied", n})
  local msg = "[RTT] matched " .. diag.tried .. ", set>0 on " .. diag.set .. ", slot1 readback: " .. tostring(diag.readback) .. ", first error: " .. tostring(diag.err)
  log(msg)
  diag = { set = 0, err = nil, readback = nil, tried = 0 }
end

script.on_event(defines.events.on_lua_shortcut, function(ev)
  if ev.prototype_name == "rtt-apply-targeting" then
    apply_all(game.get_player(ev.player_index))
  end
end)

-- auto-apply to anything newly built (player, robot, or script -- HeroTurret rank-ups raise script_raised_built)
local function on_built(ev)
  local e = ev.entity or ev.created_entity
  if e and e.valid and e.force and settings.global["rtt-auto-apply"].value then apply(e) end
end
local filter = {}
for _, t in ipairs(TURRET_TYPES) do filter[#filter + 1] = {filter = "type", type = t} end
script.on_event(defines.events.on_built_entity, on_built, filter)
script.on_event(defines.events.on_robot_built_entity, on_built, filter)
script.on_event(defines.events.script_raised_built, on_built, filter)
script.on_event(defines.events.script_raised_revive, on_built, filter)
